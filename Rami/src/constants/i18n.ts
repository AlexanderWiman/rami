/** Always use Latin numerals (0-9) regardless of language. */
export function formatNumber(_lang: Language, n: number): string {
  return String(n);
}

/** Format time HH:MM (24h) or h:MM AM/PM (12h) using Latin digits. */
export function formatTimeWithLocale(lang: Language, date: Date, use12h?: boolean): string {
  const h24 = date.getHours();
  const m = date.getMinutes();
  const padM = String(m).padStart(2, '0');
  if (!use12h) {
    return `${String(h24).padStart(2, '0')}:${padM}`;
  }
  const h12 = h24 === 0 ? 12 : h24 > 12 ? h24 - 12 : h24;
  const isPM = h24 >= 12;
  if (lang === 'ar') {
    const amPm = isPM ? 'م' : 'ص';
    return `${String(h12).padStart(2, '0')}:${padM} ${amPm}`;
  }
  const amPm = isPM ? 'PM' : 'AM';
  return `${h12}:${padM} ${amPm}`;
}

/** Format countdown HH:MM:SS with Latin digits. */
export function formatCountdownWithLocale(_lang: Language, seconds: number): string {
  const h = Math.floor(seconds / 3600);
  const m = Math.floor((seconds % 3600) / 60);
  const s = seconds % 60;
  const pad = (n: number) => String(n).padStart(2, '0');
  return [h, m, s].map(pad).join(':');
}

