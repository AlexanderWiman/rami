export type StringTranslationKey = Exclude<
  keyof (typeof translations)['en'],
  'prayers' | 'soundOptions' | 'calculationMethodOptions' | 'asrMethodOptions' | 'highLatitudeOptions'
>;

export function t(lang: Language, key: keyof (typeof translations)['en']): string {
  const dict = translations[lang];
  const val = dict[key];
  if (typeof val === 'string') return val;
  return (translations.en[key] as string) ?? String(key);
}

export function getString(lang: Language, key: StringTranslationKey): string {
  return translations[lang][key] as string;
}

export function getPrayerName(lang: Language, name: PrayerName): string {
  return translations[lang].prayers[name];
}

export function getSoundLabel(lang: Language, soundKey: string): string {
  if (soundKey === 'custom') return translations[lang].customAzan;
  const fromTranslations = translations[lang].soundOptions[soundKey];
  if (fromTranslations) return fromTranslations;
  const match = soundKey.match(/^azan(\d+)$/i);
  if (match) {
    const n = match[1];
    if (lang === 'en') return `Azan ${n}`;
    if (lang === 'ar') return `أذان ${n}`;
    if (lang === 'tr') return `Ezan ${n}`;
    if (lang === 'fr') return `Adhan ${n}`;
    if (lang === 'es') return `Adhan ${n}`;
    if (lang === 'sv') return `Adhan ${n}`;
    if (lang === 'de') return `Adhan ${n}`;
  }
  return soundKey;
}

/** Reciter display name: Arabic for ar, English for others */
export function getReciterLabel(lang: Language, reciterId: string): string {
  const reciter = QURAN_RECITERS.find((r) => r.id === reciterId);
  if (!reciter) return reciterId;
  return lang === 'ar' ? reciter.nameAr : reciter.nameEn;
}

/** UX 2.0: Time-based greeting — 05–11 morning, 11–17 day, 17–22 evening, 22–05 night. */
export function getTimeBasedGreeting(hour: number, lang: Language): string {
  let key: 'greetingMorning' | 'greetingDay' | 'greetingEvening' | 'greetingNight';
  if (hour >= 5 && hour < 11) key = 'greetingMorning';
  else if (hour >= 11 && hour < 17) key = 'greetingDay';
  else if (hour >= 17 && hour < 22) key = 'greetingEvening';
  else key = 'greetingNight';
  return getString(lang, key);
}
