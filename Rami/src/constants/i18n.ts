/** Always use Latin numerals (0-9) regardless of language. */
export function formatNumber(_lang: Language, n: number): string {
  return String(n);
}

/** Format time HH:MM using Latin digits. */
export function formatTimeWithLocale(_lang: Language, date: Date): string {
  const h = date.getHours();
  const m = date.getMinutes();
  return `${String(h).padStart(2, '0')}:${String(m).padStart(2, '0')}`;
}

/** Format countdown HH:MM:SS with Latin digits. */
export function formatCountdownWithLocale(_lang: Language, seconds: number): string {
  const h = Math.floor(seconds / 3600);
  const m = Math.floor((seconds % 3600) / 60);
  const s = seconds % 60;
  const pad = (n: number) => String(n).padStart(2, '0');
  return [h, m, s].map(pad).join(':');
}

